#!/usr/bin/env python3
"""Requirements traceability: docs/requirements.md -> docs/handoff/traceability.md.

For every requirement: the verification phases it lists (P1..P6, BENCH), the gate evidence for those
phases, and every source/test file that cites the requirement ID directly. Requirements whose only
verification is BENCH are listed for the bench plan. Exit 1 if a requirement names no verification at all.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
EVIDENCE = {"P0": "docs/toolchain-check.txt", "P1": "docs/evidence/phase1-gate.txt", "P2": "docs/evidence/phase2-gate.md",
            "P3": "docs/evidence/phase3-gate.txt", "P4": "docs/evidence/phase4-gate.txt", "P5": "docs/evidence/phase5-gate.txt",
            "P6": "docs/evidence/phase6-gate.txt", "BENCH": "docs/handoff/bench-test-plan.md"}


def requirements():
    out = []
    for line in open(os.path.join(ROOT, "docs", "requirements.md"), encoding="utf-8"):
        m = re.match(r"\|\s*((?:F|R|P|M|HW)-[A-Z0-9-]+)\s*\|(.*)\|\s*([^|]*)\|\s*$", line)
        if m:
            rid, text, ver = m.group(1), m.group(2).strip(), m.group(3).strip()
            phases = sorted(set(re.findall(r"\bP[0-9]\b|BENCH|OPEN|DEFERRED", ver)))
            out.append((rid, re.sub(r"\*\*|\[[^\]]*\]", "", text)[:90], phases, ver))
        elif re.match(r"\|\s*((?:HW)-[0-9]+)\s*\|", line):
            rid = line.split("|")[1].strip()
            out.append((rid, line.split("|")[2].strip()[:90], ["fixed"], "fixed decision"))
    return out


def citations(rid):
    r = subprocess.run(["git", "grep", "-l", "-w", rid, "--", "firmware/lib", "firmware/test", "firmware/src", "sim",
                        "tools", "hardware", "mechanical", "bom"], cwd=ROOT, capture_output=True, text=True)
    return [f for f in r.stdout.split() if f]


def main():
    rows, unverified, bench_only, open_items = [], [], [], []
    for rid, text, phases, ver in requirements():
        cites = citations(rid)
        if not phases:
            unverified.append(rid)
        if "OPEN" in phases or "DEFERRED" in phases:
            open_items.append(f"{rid} ({'open' if 'OPEN' in phases else 'deferred'})")
        if phases == ["BENCH"]:
            bench_only.append(rid)
        ev = ", ".join(f"[{p}]({os.path.relpath(os.path.join(ROOT, EVIDENCE[p]), os.path.join(ROOT, 'docs', 'handoff'))})"
                       for p in phases if p in EVIDENCE) or ver
        cite = "<br>".join(f"`{c}`" for c in cites[:4]) + (f" (+{len(cites) - 4})" if len(cites) > 4 else "")
        rows.append(f"| {rid} | {text} | {ev} | {cite or '—'} |")
    lines = ["# Requirements traceability", "", "Generated by `tools/gen_trace.py` from `docs/requirements.md`.", "",
             f"{len(rows)} requirements; {len(bench_only)} verified only on the bench; "
             f"{len(unverified)} with no verification listed{': ' + ', '.join(unverified) if unverified else ''}; "
             f"open or deferred: {', '.join(open_items) or 'none'}.", "",
             "| ID | Requirement | Verified in | Code / tests citing the ID |", "|---|---|---|---|"] + rows
    open(os.path.join(ROOT, "docs", "handoff", "traceability.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"traceability: {len(rows)} requirements, {len(bench_only)} bench-only, {len(unverified)} unverified, "
          f"open/deferred: {', '.join(open_items) or 'none'}")
    return 1 if unverified else 0


if __name__ == "__main__":
    sys.exit(main())
