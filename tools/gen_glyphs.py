#!/usr/bin/env python3
"""Generates firmware/lib/core/src/glyph_atlas.cpp: pre-shaped 1-bit images of every word the
device can show on the OLED or print, in Hindi, Telugu and Kannada, plus printable ASCII.

Why: the ESP32 cannot shape Indian scripts (conjuncts, vowel signs) at runtime, and cheap ESC/POS
printers have no Indian fonts. So every word is shaped here with HarfBuzz/raqm (via Pillow) using the
Noto fonts, and stored as a bitmap. The renderer (text_render.cpp) joins word images into lines.

Words are collected from the string literals in the source files below, so adding a phrase there and
re-running this script is all that is needed; the native test fails if a word is missing.
Requires: Pillow with raqm, fonts-noto-core.   Usage: python3 tools/gen_glyphs.py
"""
import os
import re
from PIL import Image, ImageDraw, ImageFont, features

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCES = ["firmware/lib/core/src/sms_text.cpp", "firmware/lib/core/src/print.cpp", "firmware/lib/core/src/ui.cpp"]
OUT = "firmware/lib/core/src/glyph_atlas.cpp"
FONTDIR = "/usr/share/fonts/truetype/noto/"
# size id -> (cell height px, font file style)
SIZES = {16: "Regular", 24: "Bold"}
SCRIPTS = [  # (first, last code point, font family, raqm language)
    (0x0900, 0x097F, "NotoSansDevanagari", "hi"),
    (0x0C00, 0x0C7F, "NotoSansTelugu", "te"),
    (0x0C80, 0x0CFF, "NotoSansKannada", "kn"),
]
LATIN = "NotoSans"


def script_of(word):
    for ch in word:
        cp = ord(ch)
        for lo, hi, fam, lang in SCRIPTS:
            if lo <= cp <= hi:
                return fam, lang
    return LATIN, "en"


def collect_words():
    words = set()
    lit = re.compile(r'"((?:[^"\\]|\\.)*)"')
    for rel in SOURCES:
        for s in lit.findall(open(os.path.join(ROOT, rel), encoding="utf-8").read()):
            if any(ord(c) > 0x7F for c in s):
                for w in s.split(" "):
                    if w and any(ord(c) > 0x7F for c in w):
                        words.add(w)
                        # the renderer draws glued ASCII ("(", ":", ",") separately, and phrases
                        # are also shown cut at a comma: store the bare word too
                        bare = w.rstrip("\u0964")
                        while bare and ord(bare[0]) < 0x80:
                            bare = bare[1:]
                        while bare and ord(bare[-1]) < 0x80:
                            bare = bare[:-1]
                        if bare:
                            words.add(bare)
    return sorted(words)


def fit_font(family, style, lang, words, cell):
    """Largest font size whose rendering of every word fits inside the cell height."""
    path = os.path.join(FONTDIR, f"{family}-{style}.ttf")
    for size in range(cell, 4, -1):
        f = ImageFont.truetype(path, size, layout_engine=ImageFont.Layout.RAQM)
        asc, desc = f.getmetrics()
        top = min((f.getbbox(w, language=lang)[1] for w in words), default=0)
        bottom = max((f.getbbox(w, language=lang)[3] for w in words), default=0)
        if bottom - min(top, 0) <= cell:
            return f, -min(top, 0)
    raise SystemExit(f"cannot fit {family} into {cell}px")


def render(font, offset_y, lang, text, cell):
    x0, _, x1, _ = font.getbbox(text, language=lang)
    w = max(1, x1 - min(x0, 0) + 1)
    img = Image.new("1", (w, cell), 0)
    ImageDraw.Draw(img).text((-min(x0, 0), offset_y), text, font=font, fill=1, language=lang)
    # trim empty columns on the right
    bbox = img.getbbox()
    if bbox:
        img = img.crop((0, 0, bbox[2], cell))
    return img


def pack(img):
    w, h = img.size
    wb = (w + 7) // 8
    px = img.load()
    out = bytearray(wb * h)
    for y in range(h):
        for x in range(w):
            if px[x, y]:
                out[y * wb + x // 8] |= 0x80 >> (x % 8)
    return w, bytes(out)


def main():
    assert features.check("raqm"), "Pillow must be built with raqm for Indian-script shaping"
    words = collect_words()
    ascii_chars = [chr(c) for c in range(0x21, 0x7F)]
    entries = []  # (size, text, width, bytes)
    for cell, style in SIZES.items():
        by_script = {}
        for w in words:
            by_script.setdefault(script_of(w), []).append(w)
        for (fam, lang), ws in sorted(by_script.items()):
            font, oy = fit_font(fam, style, lang, ws, cell)
            for w in ws:
                entries.append((cell, w) + pack(render(font, oy, lang, w, cell)))
        font, oy = fit_font(LATIN, style, "en", ascii_chars + ["Ág"], cell)
        for c in ascii_chars:
            entries.append((cell, c) + pack(render(font, oy, "en", c, cell)))
    entries.sort(key=lambda e: (e[0], e[1].encode("utf-8")))
    blob = bytearray()
    lines = [
        "// GENERATED by tools/gen_glyphs.py from the phrase tables. Do not edit by hand.",
        "// Fonts: Google Noto Sans / Devanagari / Telugu / Kannada (SIL Open Font License 1.1).",
        '#include "seri/text_render.h"',
        "namespace seri {",
        "namespace atlas {",
        "const GlyphEntry kEntries[] = {",
    ]
    for cell, text, w, data in entries:
        esc = text.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    {{{cell}, {w}, {len(blob)}u, "{esc}"}},')
        blob += data
    lines.append("};")
    lines.append(f"const unsigned kEntryCount = {len(entries)};")
    lines.append(f"const uint8_t kBits[{len(blob)}] = {{")
    for i in range(0, len(blob), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 24]) + ",")
    lines.append("};")
    lines.append("}  // namespace atlas")
    lines.append("}  // namespace seri")
    open(os.path.join(ROOT, OUT), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(words)} words, {len(entries)} glyph entries, {len(blob)} bytes of bitmaps -> {OUT}")


if __name__ == "__main__":
    main()
