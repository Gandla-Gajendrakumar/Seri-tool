#!/usr/bin/env python3
"""Per-supplier shopping list for N units (default 2 = the prototype set), from the same data as bom.md.

Lines that share a research item (e.g. every 0805 resistor value comes from one kit) are merged before
packs are counted, so a kit or a pack is bought once. PCB fabrication is listed separately (order 5 boards).
Usage: shopping_list.py [units]   -> bom/shopping-list-<units>units.md
"""
import math
import os
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_bom  # noqa: E402

PCB_ITEM = "PCB fabrication: 2-layer, 190 x 152 mm, 1.6 mm FR4, 1 oz, HASL, qty 5 and qty 10"


def build(units):
    sources = gen_bom.load_sources()
    need = OrderedDict()   # item -> (qty per unit summed, refs)
    for ln in gen_bom.carrier_lines() + gen_bom.offboard_lines():
        if not ln["qty"]:
            continue
        q, refs = need.get(ln["item"], (0, []))
        need[ln["item"]] = (q + ln["qty"], refs + [ln["refs"]])
    by_sup = OrderedDict()
    for item, (q, refs) in need.items():
        src = gen_bom.pick_source(sources[item])
        pieces = q * units
        pack = float(src.get("pack_qty") or 1)
        packs = math.ceil(pieces / pack - 1e-9)
        cost = packs * float(src["pack_price_inr"])
        by_sup.setdefault(src["supplier"], []).append(
            {"item": item, "mpn": sources[item].get("mpn", ""), "pieces": pieces, "pack": pack, "packs": packs,
             "pack_price": float(src["pack_price_inr"]), "cost": cost, "url": src["url"]})
    return by_sup


def render(units, by_sup):
    lines = [f"# Shopping list: {units} unit(s)", "",
             "Generated by `bom/shopping_list.py` from `bom/sources.yaml` (prices 2026-11-22; confirm before paying).",
             "Quantities are whole packs; lines sharing one pack or kit are merged.", ""]
    total = 0.0
    for sup, rows in sorted(by_sup.items(), key=lambda kv: -sum(r["cost"] for r in kv[1])):
        sub = sum(r["cost"] for r in rows)
        total += sub
        lines += [f"## {sup}: ₹{sub:,.0f}", "", "| Item | Part / model | Need | Buy | Pack price | Cost |", "|---|---|---|---|---|---|"]
        for r in rows:
            buy = f"{r['packs']} x {r['pack']:g}" if r["pack"] != 1 else f"{r['packs']:g}"
            lines.append(f"| [{r['item']}]({r['url']}) | {r['mpn']} | {r['pieces']:g} | {buy} | ₹{r['pack_price']:,.2f} | ₹{r['cost']:,.0f} |")
        lines.append("")
    lines += [f"**Total: ₹{total:,.0f}** for {units} unit(s), parts only (shipping and import duty extra).", "",
              "PCB: the line above is the per-board rate; order 5 boards from `hardware/fab/carrier-v1-gerbers.zip` "
              "(most fabs' minimum) and get a real quote by uploading the zip.", ""]
    return "\n".join(lines), total


def main(argv):
    units = int(argv[1]) if len(argv) > 1 else 2
    text, total = render(units, build(units))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), f"shopping-list-{units}units.md")
    open(out, "w").write(text)
    print(f"{units} unit(s): ₹{total:,.0f} -> {os.path.relpath(out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
